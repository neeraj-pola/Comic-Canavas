def test_older_taps_count_for_less_so_a_changed_taste_is_followed(
    conn: psycopg.Connection[Any],
) -> None:
    """80 taps preferring cooler, then 60 preferring warmer: without forgetting the 80 outvote
    the 60; with it the model follows the recent taste."""

    def switching(levels: list[int], rng: np.random.Generator) -> int:
        switching.calls += 1  # type: ignore[attr-defined]
        return int(np.argmin(levels)) if switching.calls <= 80 else int(np.argmax(levels))  # type: ignore[attr-defined]

    switching.calls = 0  # type: ignore[attr-defined]
    _seed_best_of_three(conn, "u-switch", 140, switching, np.random.default_rng(4))
    rebuild_preference(conn, "u-switch")
    stored = conn.execute("SELECT knobs FROM preference_models WHERE user_id='u-switch'").fetchone()
    assert stored is not None
    curve = {p["level"]: p["mean"] for p in stored["knobs"]["curves"]["warmth"]}
    assert curve[1.0] > curve[-1.0]  # follows the recent (warmer) taste


