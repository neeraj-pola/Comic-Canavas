def _cand(cid: str, warmth: float, identity: float = 0.8) -> Candidate:
    scores = {f: 0.5 for f in FEATURES}
    scores.update({"warmth": warmth, "identity": identity, "expression": 0.0})
    return Candidate(id=cid, panel_id=1, url=f"http://x/{cid}.png", seed=1, scores=scores)


def _state(mu_warmth: float, sd: float, *, active: bool = True) -> PreferenceState:
    mu = np.zeros(len(FEATURES))
    mu[WARMTH] = mu_warmth
    return PreferenceState(
        mu=mu,
        cov=np.eye(len(FEATURES)) * sd**2,
        scales=np.array([DEFAULT_SCALES[f] for f in FEATURES]),
        n_taps=30,
        active=active,
    )


async def _no_retry(_: int) -> list[Candidate]:
    raise AssertionError("no retry expected")


async def test_an_active_confident_model_picks_the_warmest_and_records_rewards() -> None:
    cands = [_cand("cool", 0.0), _cand("mid", 0.10), _cand("warm", 0.30)]
    final, _ = await choose_best_for_panel(
        1, cands, regenerate=_no_retry, preference=_state(3.0, 1e-3), rng=np.random.default_rng(0)
    )
    chosen = next(c for c in final if c.chosen)
    assert chosen.id == "warm"
    assert chosen.scores["explored"] == 0.0
    rewards = {c.id: c.scores["reward"] for c in final}
    assert rewards["warm"] > rewards["mid"] > rewards["cool"]  # runner-up ordering for the A/B pair


async def test_an_inactive_model_changes_nothing() -> None:
    a, b = _cand("a", 0.0, identity=0.9), _cand("b", 0.9, identity=0.7)
    with_pref, _ = await choose_best_for_panel(
        1,
        [a.model_copy(deep=True), b.model_copy(deep=True)],
        regenerate=_no_retry,
        preference=_state(3.0, 1e-3, active=False),
    )
    without, _ = await choose_best_for_panel(
        1, [a.model_copy(deep=True), b.model_copy(deep=True)], regenerate=_no_retry
    )
    assert next(c.id for c in with_pref if c.chosen) == next(c.id for c in without if c.chosen)


async def test_an_unsure_model_sometimes_explores_and_flags_it() -> None:
    explored = 0
    for seed in range(60):
        cands = [_cand("a", 0.10), _cand("b", 0.12)]
        final, _ = await choose_best_for_panel(
            1,
            cands,
            regenerate=_no_retry,
            preference=_state(0.1, 3.0),
            rng=np.random.default_rng(seed),
        )
        explored += int(next(c for c in final if c.chosen).scores["explored"])
    assert 5 < explored < 55  # neither never nor always


