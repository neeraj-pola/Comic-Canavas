def _rate_all_by_warmth(conn: psycopg.Connection[Any], user_id: str) -> int:
    """The person rates every image: warm ones great, middling ones ok, cool ones off."""
    rows = conn.execute(
        "SELECT c.day_id, c.panel_id, c.url, (c.scores->>'warmth')::float AS warmth "
        "FROM candidates c JOIN days d ON d.job_id = c.day_id WHERE d.user_id = %s",
        (user_id,),
    ).fetchall()
    for r in rows:
        rating = 2 if r["warmth"] > 0.62 else 1 if r["warmth"] > 0.4 else 0
        conn.execute(
            "INSERT INTO image_ratings (day_id, panel_id, url, rating) VALUES (%s,%s,%s,%s)",
            (r["day_id"], r["panel_id"], r["url"], rating),
        )
    conn.commit()
    return len(rows)


def test_ratings_teach_the_model_what_a_good_image_is_and_where_the_cut_points_sit(
    conn: psycopg.Connection[Any],
) -> None:
    _seed_best_of_three(conn, "u-rate", 30, _warmest, np.random.default_rng(3))
    n_rated = _rate_all_by_warmth(conn, "u-rate")

    summary = rebuild_preference(conn, "u-rate")
    conn.commit()

    ratings = summary["accuracy"]["ratings"]
    assert ratings["n"] == n_rated == 90
    assert ratings["great"] + ratings["ok"] + ratings["off"] == 90 and ratings["great"] > 0
    low, high = ratings["thresholds"]
    assert low < high  # "ok" starts below "great"
    row = conn.execute("SELECT mu FROM preference_models WHERE user_id='u-rate'").fetchone()
    assert row is not None and len(row["mu"]) == len(
        FEATURES
    )  # cut points are not stored as features
    weights = dict(zip(FEATURES, row["mu"], strict=True))
    assert weights["warmth"] == max(weights.values()) and weights["warmth"] > 0.5


