def test_rounds_drawn_by_the_bandit_feed_its_posterior_and_the_feel_good_term(
    conn: psycopg.Connection[Any],
) -> None:
    _seed_best_of_three(conn, "u-ts", 15, _warmest, np.random.default_rng(2), roles=True)
    rebuild_preference(conn, "u-ts")
    conn.commit()
    row = conn.execute("SELECT knobs FROM preference_models WHERE user_id='u-ts'").fetchone()
    assert row is not None
    posterior = row["knobs"]["ts"]
    assert len(posterior["mu"]) == 6 and len(posterior["center_mu"]) == 6
    assert set(posterior["other_arm"]) == {"1", "2"} and len(posterior["other_arm"]["1"]) == 15
    state = load_preference_state(conn, "u-ts")
    assert state is not None and state.bandit is not None and state.knob_taps == 15
    # tempered (each row counts for ETA of a comparison): wider than the plain posterior
    plain_sd = np.sqrt(np.diag(np.array(row["knobs"]["cov"])))
    tempered_sd = np.sqrt(np.diag(state.bandit.cov))
    assert np.all(tempered_sd >= plain_sd - 1e-9) and np.any(tempered_sd > plain_sd * 1.05)
