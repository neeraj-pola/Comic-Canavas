# --- model ------------------------------------------------------------------


def _planted_diffs(n: int, rng: np.random.Generator, true_w: np.ndarray) -> np.ndarray:
    """Taps generated by a person whose true taste is `true_w`."""
    x = rng.normal(size=(n, len(true_w)))
    picks_first = rng.random(n) < model.sigmoid(x @ true_w)
    return np.where(picks_first[:, None], x, -x)  # always chosen-minus-rejected


def test_model_recovers_a_planted_preference_and_gets_more_certain() -> None:
    true_w = np.zeros(len(FEATURES))
    true_w[WARMTH] = 2.0
    rng = np.random.default_rng(0)
    diffs = _planted_diffs(80, rng, true_w)

    _, cov_few = model.fit(diffs[:8])
    mu_many, cov_many = model.fit(diffs)

    assert mu_many[WARMTH] > 1.0  # found the planted taste
    assert np.argmax(np.abs(mu_many)) == WARMTH
    assert cov_many[WARMTH, WARMTH] < cov_few[WARMTH, WARMTH]  # more taps -> less unsure


def test_no_taps_returns_the_prior_and_an_unsure_model_predicts_near_a_coin_flip() -> None:
    mu, cov = model.fit(np.zeros((0, len(FEATURES))))
    assert np.allclose(mu, 0) and np.allclose(cov, np.eye(len(FEATURES)))
    assert model.predict_prob(mu, cov, np.ones(len(FEATURES))) == pytest.approx(0.5)


def test_thompson_samples_vary_but_center_on_the_mean() -> None:
    mu = np.arange(len(FEATURES), dtype=float)
    cov = np.eye(len(FEATURES)) * 0.25
    rng = np.random.default_rng(1)
    draws = np.array([model.sample_weights(mu, cov, rng) for _ in range(2000)])
    assert draws.std(axis=0).min() > 0.3
    assert np.allclose(draws.mean(axis=0), mu, atol=0.1)


