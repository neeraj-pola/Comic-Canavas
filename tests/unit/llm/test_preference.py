def test_a_single_lucky_tap_does_not_activate_the_model() -> None:
    """The gate used to be "strictly more accurate than the default" — on ~20 scored
    taps that flipped on from ONE lucky call (a 71% score on 21 taps carries a 95%
    margin of about +-20 points). It now needs a clear net edge."""
    assert not should_activate(n_taps=25, edge=1.0)  # one tap ahead: luck
    assert not should_activate(n_taps=25, edge=MIN_EDGE - 0.5)
    assert should_activate(n_taps=25, edge=MIN_EDGE)
    assert not should_activate(n_taps=MIN_TAPS - 1, edge=10.0)  # a big edge on too few taps
    assert not should_activate(n_taps=30, edge=-4.0)  # behind the default


def test_the_accuracy_summary_carries_every_number_the_page_shows(
    conn: psycopg.Connection[Any],
) -> None:
    """The page's "won X calls / net edge / matched the default on ALL taps" text is
    only honest if it is computed, not guessed — including the warm-up taps the
    head-to-head skips."""
    _seed_taps(conn, "u-summary", 30, "warmth", np.random.default_rng(9))

    acc = rebuild_preference(conn, "u-summary")["accuracy"]

    assert acc["overall_n"] == 30 and 0.0 <= acc["overall_hand"] <= 1.0
    assert acc["n_eval"] == 30 - acc["warmup"]
    # edge is exactly (calls the learned model won) - (calls the default won), ties half
    assert acc["edge"] == pytest.approx(
        acc["learned_wins"] - acc["hand_wins"], abs=acc["n_eval"] / 2
    )
    assert acc["min_edge"] == MIN_EDGE


def _gradient_norm(diffs: np.ndarray, w: np.ndarray) -> float:
    """Size of the posterior's gradient at `w`. The problem is convex, so a (near-)zero
    gradient proves `w` is THE optimum — no second optimizer needed to check against."""
    p = model.sigmoid(diffs @ w)
    return float(np.linalg.norm(-(diffs.T @ (1.0 - p)) + w / model.PRIOR_VAR))


@pytest.mark.parametrize("seed", [3, 13, 33, 57])  # people the old warm-started fit broke
def test_refitting_after_every_tap_reaches_the_true_optimum(seed: int) -> None:
    """Retraining after each tap warm-starts from the previous answer, and
    an undamped Newton step can overshoot and get stuck at a bad local
    point instead of the true optimum. These four seeds reproduce that
    failure mode; the fit must reach the true optimum regardless."""
    rng = np.random.default_rng(seed)
    n, d = 26, len(FEATURES)
    true = rng.normal(0, 2.0, d)  # a person with strong tastes
    x = rng.normal(0, 1.6, (n, d))
    picked_first = rng.random(n) < model.sigmoid(x @ true)
    diffs = np.where(picked_first[:, None], x, -x)

    mu = np.zeros(d)
    for t in range(1, n + 1):  # exactly what `rebuild_preference` does
        mu, _ = model.fit(diffs[:t], w0=mu)

    assert (
        _gradient_norm(diffs, mu) < 1e-4
    )  # a stationary point of a convex objective = the optimum
    assert np.abs(mu).max() < 8  # and never the +-15..20 garbage
    cold, _ = model.fit(diffs)
    assert np.allclose(mu, cold, atol=1e-4)  # warm-started and cold-started agree


def test_the_fit_never_increases_its_own_objective() -> None:
    """Whatever it is warm-started from — even a wild start — a step is only taken if it
    lowers the (convex) objective, so the answer can never be worse than where it began."""
    rng = np.random.default_rng(0)
    diffs = rng.normal(0, 2.0, (25, len(FEATURES)))
    wild = rng.normal(0, 15.0, len(FEATURES))

    def objective(w: np.ndarray) -> float:
        return float(np.sum(np.logaddexp(0.0, -(diffs @ w))) + 0.5 * float(w @ w))

    mu, _ = model.fit(diffs, w0=wild)

    assert objective(mu) <= objective(wild)
    assert _gradient_norm(diffs, mu) < 1e-4


# --- best-of-3 taps, the knob model, the KPI ---------------------------------------------


_EMBED_MIX = np.random.default_rng(99).normal(size=(4, 32))


def _seed_best_of_three(
    conn: psycopg.Connection[Any],
    user_id: str,
    n: int,
    choose: Any,
    rng: np.random.Generator,
    *,
    start: datetime = datetime(2026, 9, 1, tzinfo=UTC),
    pick_feature: str | None = None,
    pick_embedding: bool = False,
    roles: bool = False,
) -> None:
    """`n` days, one panel each, three candidates that differ only in warmth level (-1/0/+1)
    exactly as the generator makes them; `choose(levels, rng)` returns which one is picked.
    A tap writes one `image_pairs` row per option passed on, sharing a `tap_id`."""
    conn.execute("INSERT INTO users (id, email) VALUES (%s, NULL)", (user_id,))
    for i in range(n):
        job = f"{user_id}:{i}"
        conn.execute(
            "INSERT INTO jobs (id, user_id, kind, status) VALUES (%s,%s,'daily','done')",
            (job, user_id),
        )
        conn.execute(
            "INSERT INTO days (job_id, user_id, date, source) VALUES (%s,%s,%s,'text')",
            (job, user_id, (start + timedelta(days=i)).date()),
        )
        conn.execute(
            "INSERT INTO beats (day_id, beat_id, time, place, event, emotion, importance, humor) "
            "VALUES (%s,'b1','morning','desk','e','calm',0.5,0.5)",
            (job,),
        )
        conn.execute(
            "INSERT INTO panels (day_id, panel_id, beat_id, place, time_of_day, expression, "
            "action, framing, caption_a) "
            "VALUES (%s,1,'b1','desk','morning','neutral','a','wide','c')",
            (job,),
        )
        levels = [-1, 0, 1]
        feature_values: list[float] = []
        latents: list[float] = []
        for j, level in enumerate(levels):
            scores = {
                f: float(rng.uniform(0.2, 0.9)) for f in FEATURES[:10]
            }  # critic + pixel + axis
            if pick_feature is not None:
                feature_values.append(scores[pick_feature])
            scores.update(
                {
                    "axis_id": 0.0,
                    "axis_level": float(level),
                    "offset": float(level),
                    "level_warmth": float(level),
                    "level_closeness": 0.0,
                    "level_expression": 0.0,
                    "expression": 0.0,
                    "phrased": 1.0,
                }
            )
            if roles:  # the bandit's design: the guess (0) between two exploratory draws (1, 2)
                scores["role"] = float((1, 0, 2)[j])
            embedding_json = None
            if pick_embedding:  # a low-rank "image embedding": 4 hidden factors spread over 32 dims
                latent = rng.normal(size=4)
                latents.append(float(latent[0]))
                vector = latent @ _EMBED_MIX + rng.normal(scale=0.05, size=32)
                embedding_json = psycopg.types.json.Json([round(float(x), 5) for x in vector])
            conn.execute(
                "INSERT INTO candidates (id, day_id, panel_id, url, seed, scores, embedding) "
                "VALUES (%s,%s,1,%s,%s,%s,%s)",
                (
                    f"{job}-{j}",
                    job,
                    f"http://x/{job}-{j}.png",
                    j,
                    psycopg.types.json.Json(scores),
                    embedding_json,
                ),
            )
        pick = choose(levels, rng)
        if pick_embedding:
            pick = int(np.argmax(latents))
        if pick_feature is not None:  # a taste for a measured feature instead of a knob level
            pick = int(np.argmax(feature_values))
        for j in range(3):
            if j != pick:
                conn.execute(
                    "INSERT INTO image_pairs (day_id, panel_id, chosen, rejected, source, tap_id, "
                    "created_at) VALUES (%s,1,%s,%s,'ab',%s,%s)",
                    (
                        job,
                        f"http://x/{job}-{pick}.png",
                        f"http://x/{job}-{j}.png",
                        f"tap-{job}",
                        start + timedelta(days=i, hours=1),
                    ),
                )
    conn.commit()


