def _seed_taps(
    conn: psycopg.Connection[Any], user_id: str, n: int, prefer: str, rng: np.random.Generator
) -> None:
    """`n` days, one panel each, two candidates with random features; the
    tapped one is the warmer (`prefer="warmth"`) or the hand-set reward's
    favourite (`prefer="hand"`)."""
    conn.execute("INSERT INTO users (id, email) VALUES (%s, NULL)", (user_id,))
    start = datetime(2026, 9, 1, tzinfo=UTC)
    for i in range(n):
        job = f"{user_id}:{i}"
        conn.execute(
            "INSERT INTO jobs (id, user_id, kind, status) VALUES (%s,%s,'daily','done')",
            (job, user_id),
        )
        conn.execute(
            "INSERT INTO days (job_id, user_id, date, source) VALUES (%s,%s,%s,'text')",
            (job, user_id, (start + timedelta(days=i)).date()),
        )
        conn.execute(
            "INSERT INTO beats (day_id, beat_id, time, place, event, emotion, importance, humor) "
            "VALUES (%s,'b1','morning','desk','e','calm',0.5,0.5)",
            (job,),
        )
        conn.execute(
            "INSERT INTO panels (day_id, panel_id, beat_id, place, time_of_day, expression, "
            "action, framing, caption_a) "
            "VALUES (%s,1,'b1','desk','morning','neutral','a','wide','c')",
            (job,),
        )
        pair: list[dict[str, float]] = []
        for j in range(2):
            scores = {
                f: float(rng.uniform(0.2, 0.9)) for f in FEATURES[:10]
            }  # critic + pixel + axis
            scores["expression"] = 0.0
            pair.append(scores)
            conn.execute(
                "INSERT INTO candidates (id, day_id, panel_id, url, seed, scores) "
                "VALUES (%s,%s,1,%s,%s,%s)",
                (f"{job}-{j}", job, f"http://x/{job}-{j}.png", j, psycopg.types.json.Json(scores)),
            )
        if prefer == "warmth":
            win = 0 if pair[0]["warmth"] > pair[1]["warmth"] else 1
        else:
            from app.critic.reward_head import score

            def hand(s: dict[str, float]) -> float:
                return score(Candidate(id="t", panel_id=1, url="u", seed=1, scores=s))

            win = 0 if hand(pair[0]) > hand(pair[1]) else 1
        conn.execute(
            "INSERT INTO image_pairs (day_id, panel_id, chosen, rejected, source, created_at) "
            "VALUES (%s,1,%s,%s,'ab',%s)",
            (
                job,
                f"http://x/{job}-{win}.png",
                f"http://x/{job}-{1 - win}.png",
                start + timedelta(days=i, hours=1),
            ),
        )
    conn.commit()


def test_a_person_who_likes_warm_images_gets_an_active_ranking_model(
    conn: psycopg.Connection[Any],
) -> None:
    _seed_taps(conn, "u-warm", 40, "warmth", np.random.default_rng(3))

    summary = rebuild_preference(conn, "u-warm")
    conn.commit()

    assert summary["n_taps"] == 40
    assert summary["active"] is True  # beat the hand-set weights on held-out taps
    assert summary["accuracy"]["learned"] > summary["accuracy"]["hand"]
    state = load_preference_state(conn, "u-warm")
    # (`lean` is the knob model's, not this model's: these candidates carry no knob levels,
    # so it has nothing to learn from — see the best-of-3 tests below.)
    assert (
        state is not None
        and state.active
        and state.lean
        == {
            "warmth": 0,
            "closeness": 0,
            "expression": 0,
        }
    )
    snaps = conn.execute(
        "SELECT tap_index, prob, correct FROM preference_snapshots WHERE user_id='u-warm' "
        "ORDER BY tap_index"
    ).fetchall()
    assert [s["tap_index"] for s in snaps] == list(range(1, 41))
    assert np.mean([s["correct"] for s in snaps[-15:]]) >= 0.75  # late taps predicted well


